class TestSuiteManager:
    """Loads and grades benchmark questions."""
    __test__ = False

    def __init__(self, path: Optional[Path] = None):
        self.path = path or (config.data_dir / "test_suite.json")
        self.questions: List[BenchmarkQuestion] = []
        self.load()

    def load(self) -> List[BenchmarkQuestion]:
        with open(self.path, "r", encoding="utf-8") as f:
            raw = json.load(f)
            self.questions = [BenchmarkQuestion(**item) for item in raw]
        return self.questions

    def grade_answer(
        self,
        question: BenchmarkQuestion,
        answer_text: str,
        citations_found: List[str],
    ) -> AnswerGrade:
        """Evaluates an answer against ground truth requirements."""
        answer_lower = answer_text.lower()
        has_refusal_phrase = any(
            p in answer_lower
            for p in [
                "papers do not say",
                "not in the papers",
                "cannot answer from",
                "does not mention",
                "not covered in the provided",
                "does not contain information",
            ]
        )

        if question.must_refuse:
            if has_refusal_phrase:
                return AnswerGrade.REFUSED_CORRECTLY
            else:
                return AnswerGrade.REFUSED_WRONGLY

        # Grounded question
        if has_refusal_phrase:
            return AnswerGrade.REFUSED_WRONGLY

        # Check for citation and keyword matches
        matches = [kw.lower() in answer_lower for kw in question.expected_keywords]
        match_rate = sum(matches) / max(1, len(matches))

        # Check if citations exist
        has_citation = len(citations_found) > 0 or ("(" in answer_text and ")" in answer_text)

        if match_rate >= 0.4 and has_citation:
            return AnswerGrade.CORRECT
        else:
            return AnswerGrade.WRONG
